import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

// Only derivatives live here. Canonical artwork is never modified.
export async function generateArtwork(sourceDir, outputDir) {
  const names = (await fs.readdir(sourceDir)).filter(name =>
    !name.startsWith('.') && !name.startsWith('bryen') && /\.(png|webp|svg)$/i.test(name)
  ).sort();
  await fs.mkdir(outputDir, { recursive: true });
  const manifest = {};
  const imports = [];
  const entries = [];
  const generated = new Set(['index.js']);
  // Each image also gets its own module (`<name>.js`). index.js aggregates them
  // for the Work page; the home page imports only the few it shows, so the rest
  // of the library stays out of the entry bundle.
  const writeImageModule = async (index, name, variants, fallback) => {
    const module = `${name}.js`;
    const lines = variants.map(v => `import ${v.binding} from ${JSON.stringify(v.file.startsWith('../') ? v.file : `./${v.file}`)};`);
    const srcSet = variants.map(v => `${v.binding} + ' ${v.width}w'`).join(" + ', ' + ");
    await fs.writeFile(path.join(outputDir, module), `// Generated by scripts/generate-artwork.mjs. Do not edit.\n${lines.join('\n')}\nexport default { src: ${fallback.binding}, srcSet: ${srcSet}, width: ${fallback.width}, height: ${fallback.height} };\n`);
    generated.add(module);
    imports.push(`import image${index} from ${JSON.stringify(`./${module}`)};`);
    entries.push(`${JSON.stringify(name)}: image${index}`);
  };
  for (const [index, name] of names.entries()) {
    const source = path.join(sourceDir, name);
    const metadata = await sharp(source).metadata();

    // Keep SVG sources browser-rendered. Sharp can read SVG dimensions, but
    // flattening an SVG that embeds an approved screenshot can discard the
    // nested image detail. Vite handles the canonical SVG directly instead.
    if (/\.svg$/i.test(name)) {
      const width = metadata.width;
      const height = metadata.height;
      if (!width || !height) throw new Error(`SVG artwork must declare dimensions: ${name}`);
      const file = `../${name}`;
      const variants = [{ file, width, height, binding: 'svg' }];
      manifest[name] = { variants };
      await writeImageModule(index, name, variants, variants[0]);
      continue;
    }

    const maxWidth = Math.min(metadata.width, 1920);
    const widths = [...new Set([480, 800, 1280, maxWidth].filter(width => width <= maxWidth))].sort((a, b) => a - b);
    const variants = [];
    for (const width of widths) {
      const file = `${name}-${width}.webp`;
      const info = await sharp(source).resize({ width, withoutEnlargement: true }).webp({ quality: 85 }).toFile(path.join(outputDir, file));
      variants.push({ file, width: info.width, height: info.height, binding: `w${width}` });
      generated.add(file);
    }
    const fallback = variants.find(v => v.width === 1280) ?? variants.at(-1);
    manifest[name] = { variants };
    await writeImageModule(index, name, variants, fallback);
  }
  await fs.writeFile(path.join(outputDir, 'index.js'), `// Generated by scripts/generate-artwork.mjs. Do not edit.\n${imports.join('\n')}\nexport const artwork = {\n${entries.join(',\n')}\n};\n`);
  // Remove obsolete derivatives and image modules after a canonical file is replaced or renamed.
  for (const file of await fs.readdir(outputDir)) {
    if (!generated.has(file) && /\.(webp|js)$/.test(file)) await fs.unlink(path.join(outputDir, file));
  }
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = fileURLToPath(new URL('../src/assets/photos/', import.meta.url));
  const manifest = await generateArtwork(source, path.join(source, 'generated'));
  console.log(`Generated responsive artwork for ${Object.keys(manifest).length} canonical images.`);
}
